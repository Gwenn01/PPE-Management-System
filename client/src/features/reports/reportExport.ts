import type { ReportResult } from '../../services/reportingService'
export const reportCell = (value: string | number | null, money = false) => money && typeof value === 'number'
  ? (value / 100).toFixed(2) : String(value ?? '')
const spreadsheetText = (v: string) => /^[=+@\-\t\r]/.test(v) ? `'${v}` : v
const name = (r: ReportResult) => `PPE_${r.type}_${r.municipalityId}_${r.filters.end}`

/** Both exports consume the same authorized report snapshot returned by the service. */
export async function downloadExcel(report: ReportResult) {
  const XLSX = await import('xlsx')
  const sheet = XLSX.utils.aoa_to_sheet([
    ['PPE Management System — ' + report.type],
    ['Municipality', report.municipalityId], ['Generated', report.generatedAt], ['Generated by', report.generatedBy],
    ['Period', `${report.filters.start} to ${report.filters.end}`], [],
    report.columns.map(c => c.label),
    ...report.rows.map(r => report.columns.map(c => c.money ? Number(r[c.key] ?? 0) / 100 : typeof r[c.key] === 'string' ? spreadsheetText(String(r[c.key])) : r[c.key] ?? '')),
    report.columns.map((c,i) => i === 0 ? 'TOTAL' : c.money ? (report.totals[c.key] ?? 0) / 100 : ''),
  ])
  sheet['!cols'] = report.columns.map(c => ({ wch: Math.max(20, c.label.length + 4) }))
  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, sheet, 'Report')
  XLSX.writeFile(workbook, name(report) + '.xlsx')
}

export async function downloadPdf(report: ReportResult) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')])
  const doc = new jsPDF({ orientation: report.columns.length > 6 ? 'landscape' : 'portrait' })
  doc.setFontSize(14)
  doc.text('PPE Management System — ' + report.type.replaceAll('_',' ').toUpperCase(), 14, 15)
  doc.setFontSize(9)
  doc.text(`Municipality: ${report.municipalityId} | Period: ${report.filters.start} to ${report.filters.end}`,14,23)
  doc.text(`Generated: ${report.generatedAt} | By: ${report.generatedBy}`,14,29)
  autoTable(doc, { startY: 35, head: [report.columns.map(c=>c.label)],
    body: [...report.rows.map(r=>report.columns.map(c=>reportCell(r[c.key],c.money))), report.columns.map((c,i)=> i===0?'TOTAL': c.money ? reportCell(report.totals[c.key]??0,true):'')],
    styles: { fontSize: 7, overflow:'linebreak' }, theme: 'striped' })
  doc.save(name(report)+'.pdf')
}
